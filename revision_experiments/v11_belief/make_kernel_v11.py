"""Generate kernel_v11.py: the registered v10 kernel derivation (S1-S12, from unmodified v7 run_trial)
plus S13, a bounded re-observation used only while a belief-based completion state is ambiguous.
Rules without `wants_reobservation` (commit_only, revocable, reactive) execute exactly the v10 kernel."""
from pathlib import Path
import hashlib, importlib.util, json
HERE = Path(__file__).resolve().parent; V10 = HERE.parent/'v10_studyC'; V7 = HERE.parent/'v7'/'ablation_runner.py'

spec = importlib.util.spec_from_file_location('v10_make_kernel', V10/'make_kernel.py'); mk = importlib.util.module_from_spec(spec); spec.loader.exec_module(mk)
REGISTERED = json.loads((V10/'kernel_derivation.json').read_text(encoding='utf-8'))['substitutions']
assert [s['id'] for s in REGISTERED] == [f'S{i}' for i in range(1, 13)]
S13 = ("""            obs,invalidated=observe('before_decision')
            if invalidated:recovery('progress_revoked_before_decision')
""", """            obs,invalidated=observe('before_decision')
            if invalidated:recovery('progress_revoked_before_decision')
            reobserved=0  # v11/S13: bounded re-observation while a completion belief is ambiguous
            while getattr(memory,'wants_reobservation',lambda:False)() and reobserved<2:
                reobserved+=1;journal.emit('belief_reobservation',number=reobserved,wait_seconds=.25);time.sleep(.25)
                obs,invalidated=observe('belief_reobservation')
                if invalidated:recovery('progress_revoked_before_decision')
""")
OLD_IMPORT = 'from memory_rules import make_memory, WatchdogNoise\n'
NEW_IMPORT = ("V10 = Path(__file__).resolve().parent.parent/'v10_studyC'\n"
              "if str(V10) not in sys.path:\n    sys.path.insert(0, str(V10))\n"
              "from belief_rules import make_memory, WatchdogNoise\n")


def main():
    header = mk.HEADER.replace('Study C trial kernel (generated by make_kernel.py', 'v11 trial kernel (generated by make_kernel_v11.py')
    header = header.replace('S1-S8 original Study C changes, S9-S12 amendment A1.', 'S1-S8 original Study C changes, S9-S12 amendment A1, S13 v11 belief re-observation.')
    assert header.count(OLD_IMPORT) == 1; header = header.replace(OLD_IMPORT, NEW_IMPORT)
    src = V7.read_text(encoding='utf-8'); body = src[src.index('def run_trial('):src.index('def precheck(')]
    subs = [(s['old'], s['new']) for s in REGISTERED]+[S13]
    for a, b in subs:
        assert body.count(a) == 1, a[:80]
        body = body.replace(a, b)
    (HERE/'kernel_v11.py').write_text(header+body.rstrip()+'\n', encoding='utf-8')
    (HERE/'kernel_v11_derivation.json').write_text(json.dumps({'source': '../v7/ablation_runner.py',
        'source_sha256': hashlib.sha256(src.encode('utf-8')).hexdigest(), 'base': '../v10_studyC/kernel_derivation.json (S1-S12)',
        'substitutions': [{'id': f'S{i+1}', 'old': a, 'new': b} for i, (a, b) in enumerate(subs)]}, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'kernel_v11.py generated with {len(subs)} substitutions')


if __name__ == '__main__':
    main()
