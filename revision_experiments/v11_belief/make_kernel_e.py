"""Generate kernel_e.py: identical to kernel_d.py (S1-S14) except that rules come from study_e_rules."""
from pathlib import Path
HERE = Path(__file__).resolve().parent


def main():
    s = (HERE/'kernel_d.py').read_text(encoding='utf-8')
    for a, b in [('Study D trial kernel (generated by make_kernel_d.py', 'Study E trial kernel (generated by make_kernel_e.py from kernel_d.py'),
                 ('from study_d_rules import make_memory, make_noise\n', 'from study_e_rules import make_memory, make_noise\n')]:
        assert s.count(a) == 1, a
        s = s.replace(a, b)
    (HERE/'kernel_e.py').write_text(s, encoding='utf-8'); print('kernel_e.py generated')


if __name__ == '__main__':
    main()
