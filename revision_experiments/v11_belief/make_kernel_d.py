"""Generate kernel_d.py = kernel_v11 derivation (S1-S13) + S14: the noise generator also takes the unit's error persistence."""
from pathlib import Path
import hashlib, importlib.util, json
HERE = Path(__file__).resolve().parent; V7 = HERE.parent/'v7'/'ablation_runner.py'
spec = importlib.util.spec_from_file_location('mk11', HERE/'make_kernel_v11.py'); mk11 = importlib.util.module_from_spec(spec); spec.loader.exec_module(mk11)
S14 = ("noise=WatchdogNoise(manifest['protocol_id'],scenario['seed'],unit['noise_type'],unit['noise_rate'])",
       "noise=make_noise(manifest['protocol_id'],scenario['seed'],unit)  # Study D/S14: persistence-aware errors")


def main():
    header = mk11.mk.HEADER.replace('Study C trial kernel (generated by make_kernel.py', 'Study D trial kernel (generated by make_kernel_d.py')
    header = header.replace('S1-S8 original Study C changes, S9-S12 amendment A1.', 'S1-S8 Study C, S9-S12 amendment A1, S13 belief re-observation, S14 persistent errors.')
    new_import = mk11.NEW_IMPORT.replace('from belief_rules import make_memory, WatchdogNoise\n', 'from study_d_rules import make_memory, make_noise\n')
    assert header.count(mk11.OLD_IMPORT) == 1; header = header.replace(mk11.OLD_IMPORT, new_import)
    src = V7.read_text(encoding='utf-8'); body = src[src.index('def run_trial('):src.index('def precheck(')]
    subs = [(s['old'], s['new']) for s in mk11.REGISTERED]+[mk11.S13, S14]
    for a, b in subs:
        assert body.count(a) == 1, a[:80]
        body = body.replace(a, b)
    (HERE/'kernel_d.py').write_text(header+body.rstrip()+'\n', encoding='utf-8')
    (HERE/'kernel_d_derivation.json').write_text(json.dumps({'source': '../v7/ablation_runner.py', 'source_sha256': hashlib.sha256(src.encode('utf-8')).hexdigest(),
        'substitutions': [{'id': f'S{i+1}', 'old': a, 'new': b} for i, (a, b) in enumerate(subs)]}, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'kernel_d.py generated with {len(subs)} substitutions')


if __name__ == '__main__':
    main()
